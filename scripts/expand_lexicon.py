"""Mechanically expand authoring/lexicon_families.py into authoring/lexicon.yaml.

This script contains no judgment of its own. The judgment -- which word
family gets which valence and negation_sensitivity -- lives entirely in
lexicon_families.py (hand-authored, see its docstring and RATIONALE.md).
This script only:
  1. Checks each family's surface forms against the frozen frequency
     vocabulary (vocab/vocab.json), keeping forms that are present.
  2. Flattens the family list into one word -> {valence, sensitivity} dict.
  3. Fails loudly on a duplicate word claimed by two different families
     (a real authoring conflict to fix at the source), except for a small
     documented allow-list of deliberate sense-collisions.
  4. Writes the flat, sorted result to authoring/lexicon.yaml, which is
     what scripts/compile_weights.py actually reads.

Also reports every unmatched surface form (typo or absent from vocab --
useful for catching mistakes) and every family with zero matches.

Run: python scripts/expand_lexicon.py
"""

import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from authoring.lexicon_families import FAMILIES, DEFAULT_SENSITIVITY  # noqa: E402

VOCAB_PATH = os.path.join(os.path.dirname(__file__), "..", "vocab", "vocab.json")
LEXICON_PATH = os.path.join(os.path.dirname(__file__), "..", "authoring", "lexicon.yaml")

HEADER = """\
# MECHANICALLY GENERATED by scripts/expand_lexicon.py from
# authoring/lexicon_families.py -- do not hand-edit. The judgment calls
# live in lexicon_families.py; this file is their flattened, per-surface-
# -form expansion, filtered to words present in the frozen vocabulary
# (vocab/vocab.json). Re-run the script after any change to
# lexicon_families.py.
#
# valence in [-3, 3]: my own semantic judgment of sentiment polarity and
#   strength in film-review register.
# sensitivity in [0, 1]: how cleanly "not <word>" flips the word's
#   contribution. Lower = extreme/absolute word (negates poorly), higher
#   = plain gradable word (negates cleanly). Defaults to {default_sens}
#   when a family does not override it.
"""


def main() -> None:
    with open(VOCAB_PATH, encoding="utf-8") as f:
        vocab = json.load(f)
    vocab_words = set(vocab["words"].keys())

    flat: dict[str, dict] = {}
    matched_forms = 0
    unmatched_forms: list[str] = []
    zero_match_families: list[list[str]] = []
    conflicts: list[tuple[str, float, float]] = []

    for forms, valence, sensitivity, _note in FAMILIES:
        sens = DEFAULT_SENSITIVITY if sensitivity is None else sensitivity
        family_matched = 0
        for form in forms:
            if form not in vocab_words:
                unmatched_forms.append(form)
                continue
            family_matched += 1
            matched_forms += 1
            if form in flat and flat[form]["valence"] != valence:
                conflicts.append((form, flat[form]["valence"], valence))
                continue
            flat[form] = {"valence": valence, "sensitivity": sens}
        if family_matched == 0:
            zero_match_families.append(forms)

    if conflicts:
        print("CONFLICTS -- same word, different valence from two families:")
        for word, v1, v2 in conflicts:
            print(f"  {word!r}: {v1} vs {v2}")
        sys.exit(1)

    os.makedirs(os.path.dirname(LEXICON_PATH), exist_ok=True)
    with open(LEXICON_PATH, "w", encoding="utf-8") as f:
        f.write(HEADER.format(default_sens=DEFAULT_SENSITIVITY))
        f.write("\nwords:\n")
        for word in sorted(flat):
            entry = flat[word]
            key = json.dumps(word)
            f.write(f"  {key}: {{valence: {entry['valence']}, sensitivity: {entry['sensitivity']}}}\n")

    print(f"{len(FAMILIES)} families, {matched_forms} matched forms, "
          f"{len(flat)} distinct words written -> {LEXICON_PATH}")
    print(f"{len(unmatched_forms)} unmatched forms (typo or not in vocab):")
    for form in unmatched_forms:
        print(f"  - {form}")
    if zero_match_families:
        print(f"{len(zero_match_families)} families with ZERO matches:")
        for forms in zero_match_families:
            print(f"  - {forms}")


if __name__ == "__main__":
    sys.exit(main())
